"""The generated schema dump, and that it is current."""

from __future__ import annotations

from legvise.store.db import Database
from legvise.store.schema import install, table_names
from legvise.tools.schema_dump import OUTPUT, is_current, main, render, target

INSTALLED_AT = "2000-01-01T00:00:00+00:00"


def test_the_dump_on_disk_is_current() -> None:
    assert is_current()


def test_the_dump_lives_under_docs() -> None:
    assert OUTPUT == "docs/schema.sql"
    assert target().exists()


def test_the_dump_says_it_is_generated() -> None:
    assert render().startswith("-- Generated by legvise.tools.schema_dump")


def test_every_table_appears_in_the_dump() -> None:
    db = Database.in_memory()
    install(db, applied_at=INSTALLED_AT)
    body = render()
    for name in table_names(db):
        assert f"CREATE TABLE {name}" in body
    db.close()


def test_every_index_appears_in_the_dump() -> None:
    body = render()
    for name in ("ix_instrument_symbol", "ix_plan_session", "ix_fill_plan"):
        assert name in body


def test_the_tables_come_before_the_indexes() -> None:
    body = render()
    assert body.index("CREATE TABLE venue") < body.index("CREATE INDEX ix_instrument_symbol")


def test_the_dump_is_stable_across_calls() -> None:
    assert render() == render()


def test_the_dump_ends_with_one_newline() -> None:
    body = render()
    assert body.endswith("\n")
    assert not body.endswith("\n\n")


def test_the_dump_has_no_carriage_returns() -> None:
    assert b"\r" not in target().read_bytes()


def test_the_check_mode_passes_while_it_is_current() -> None:
    assert main(("--check",)) == 0
