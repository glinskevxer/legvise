"""Write the layer map out, generated from the imports that make it true.

An architecture diagram drawn by hand is a description of what somebody meant.
This one is a description of what the code does: the layers come from
`check_layers`, the module counts from the tree, and the dependency edges from
the imports each module actually has.

The useful column is **depends on**. A layer that imports from four of the five
below it is doing something; one that imports from one is either well isolated
or barely used, and the module count next to it says which.
"""

from __future__ import annotations

import sys
from pathlib import Path

from legvise.tools.check_layers import LAYERS, layer_of
from legvise.tools.check_wiring import reachable
from legvise.tools.walk import repo_root, source_files

__all__ = ["OUTPUT", "edges", "main", "render"]

OUTPUT = "docs/architecture.md"

BLURBS = {
    "base": "decimals, identifiers, the clock, the rule book",
    "model": "the records, and what they refuse to be",
    "store": "SQLite, migrations, one repository per aggregate",
    "domain": "depth, staleness, fees, bands, caps, transfer routes",
    "scan": "the cross venue and triangular passes, and attribution",
    "report": "session, edge, inventory and desk reports",
    "cli": "the command tree",
    "tools": "the checks, and the documents they generate",
}


def modules_by_layer() -> dict[str, list[str]]:
    """Every module grouped by the layer it belongs to."""
    found: dict[str, list[str]] = {name: [] for name, _ in LAYERS}
    for source in source_files():
        if source.is_package_init:
            continue
        layer = layer_of(source.module)
        if layer is not None:
            found[layer].append(source.module)
    return {name: sorted(items) for name, items in found.items()}


def edges() -> dict[str, set[str]]:
    """Which layers each layer imports from, itself excluded."""
    found: dict[str, set[str]] = {name: set() for name, _ in LAYERS}
    for source in source_files():
        here = layer_of(source.module)
        if here is None:
            continue
        for imported in source.imports():
            there = layer_of(imported)
            if there is not None and there != here:
                found[here].add(there)
    return found


def render() -> str:
    """The whole layer map as markdown."""
    grouped = modules_by_layer()
    dependencies = edges()
    live = reachable()
    lines = [
        "# Architecture",
        "",
        "Generated by `legvise.tools.build_architecture`. Do not edit.",
        "",
        "Layers are listed lowest first. A module may import from its own layer",
        "or any lower one, and `check_layers` refuses anything else.",
        "",
        "| layer | modules | reachable | depends on | holds |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, _ in LAYERS:
        members = grouped[name]
        alive = sum(1 for module in members if module in live)
        depends = ", ".join(f"`{item}`" for item in sorted(dependencies[name])) or "-"
        lines.append(
            f"| `{name}` | {len(members)} | {alive} | {depends} | {BLURBS.get(name, '')} |"
        )
    lines.append("")
    for name, _ in LAYERS:
        lines.append(f"## `{name}`")
        lines.append("")
        for module in grouped[name]:
            lines.append(f"- `{module}`")
        lines.append("")
    total = sum(len(items) for items in grouped.values())
    lines.append(f"{total} modules across {len(LAYERS)} layers.")
    return "\n".join(lines) + "\n"


def target() -> Path:
    """Where the map is written."""
    return repo_root() / OUTPUT


def write() -> int:
    """Write the map and return how many modules it covered."""
    path = target()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(), encoding="utf-8", newline="\n")
    return sum(len(items) for items in modules_by_layer().values())


def is_current() -> bool:
    """True when the file on disk matches what the imports produce."""
    path = target()
    return path.exists() and path.read_text(encoding="utf-8") == render()


def main(argv: tuple[str, ...] = ()) -> int:
    """Write the map, or check it is current."""
    args = argv or tuple(sys.argv[1:])
    if "--check" in args:
        if is_current():
            print("build_architecture: current")
            return 0
        print(f"build_architecture: {OUTPUT} is stale; run legvise.tools.build_architecture")
        return 1
    count = write()
    print(f"build_architecture: wrote {count} modules to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
