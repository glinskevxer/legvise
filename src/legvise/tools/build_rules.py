"""Write the rule book out as a document, generated from the code that holds it.

The rule book an operator reads and the rule book the scanner enforces have to
be the same rule book. The only way to guarantee that is to generate the first
from the second, so this walks `legvise.rules` for the clauses and the package
source for the places each one is raised, and writes both into `docs/rules.md`.

The "raised in" column is the part worth having. A clause with one call site is
a rule with one gate; a clause with five is worth reading twice, because five
gates that are meant to enforce the same rule usually enforce four.

`--check` compares instead of writing, which is what CI runs.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

from legvise.rules import Clause, clause, clause_codes, clauses_for_stage, stages
from legvise.tools.walk import repo_root, source_files

__all__ = ["OUTPUT", "call_sites", "main", "render"]

OUTPUT = "docs/rules.md"
EXEMPT_MODULES = ("legvise.tools",)


def call_sites() -> dict[str, tuple[str, ...]]:
    """Where each clause is raised, keyed by code and sorted."""
    found: dict[str, set[str]] = {code: set() for code in clause_codes()}
    for source in source_files():
        if source.module.startswith(EXEMPT_MODULES):
            continue
        for node in ast.walk(source.tree):
            if not isinstance(node, ast.Call):
                continue
            name = node.func.id if isinstance(node.func, ast.Name) else None
            if name != "refuse" or not node.args:
                continue
            first = node.args[0]
            if isinstance(first, ast.Constant) and first.value in found:
                found[first.value].add(source.module.removeprefix("legvise."))
    return {code: tuple(sorted(sites)) for code, sites in found.items()}


def _row(item: Clause, sites: tuple[str, ...]) -> str:
    where = ", ".join(f"`{site}`" for site in sites) if sites else "-"
    return f"| `{item.code}` | {item.text} | {where} |"


def render() -> str:
    """The whole rule book as markdown."""
    sites = call_sites()
    lines = [
        "# Rule book",
        "",
        "Generated by `legvise.tools.build_rules`. Do not edit.",
        "",
        "Every refusal the pricing path makes quotes one of these. The code is",
        "stored on the plan, so a week later somebody can count how often each",
        "one fired and act on the answer.",
        "",
    ]
    for stage in stages():
        lines.append(f"## {stage}")
        lines.append("")
        lines.append("| clause | says | raised in |")
        lines.append("| --- | --- | --- |")
        for item in clauses_for_stage(stage):
            lines.append(_row(item, sites[item.code]))
        lines.append("")
    lines.append(f"{len(clause_codes())} clauses across {len(stages())} stages.")
    return "\n".join(lines) + "\n"


def target() -> Path:
    """Where the document is written."""
    return repo_root() / OUTPUT


def write() -> int:
    """Write the document and return how many clauses it covered."""
    path = target()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(), encoding="utf-8", newline="\n")
    return len(clause_codes())


def is_current() -> bool:
    """True when the file on disk matches what the rule book produces."""
    path = target()
    return path.exists() and path.read_text(encoding="utf-8") == render()


def undocumented() -> tuple[str, ...]:
    """Clauses the document would show with no call site."""
    return tuple(code for code, sites in call_sites().items() if not sites)


def main(argv: tuple[str, ...] = ()) -> int:
    """Write the rule book, or check it is current."""
    args = argv or tuple(sys.argv[1:])
    if "--check" in args:
        if is_current():
            print("build_rules: current")
            return 0
        print(f"build_rules: {OUTPUT} is stale; run legvise.tools.build_rules")
        return 1
    count = write()
    print(f"build_rules: wrote {count} clauses to {OUTPUT}")
    return 0


def clause_text(code: str) -> str:
    """One clause's wording, for a caller that only has the code."""
    return clause(code).text


if __name__ == "__main__":
    sys.exit(main())
