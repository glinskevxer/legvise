"""Write the command reference out, generated from the tree itself.

`legvise --help` shows the groups and `legvise venue --help` shows one group's
commands, which means learning the surface takes forty invocations. This is the
same information on one page, and because it is generated it cannot describe a
command that was renamed.

Options are listed with their defaults, because the default is the part an
operator most often wants and most often has to run the command to find.
"""

from __future__ import annotations

import sys
from pathlib import Path

import click

from legvise.cli.main import cli
from legvise.tools.walk import repo_root

__all__ = ["OUTPUT", "commands", "main", "render"]

OUTPUT = "docs/commands.md"


def commands() -> list[tuple[str, click.Command]]:
    """Every group and command in the tree, in the order help lists them."""
    found: list[tuple[str, click.Command]] = []
    for name, group in sorted(cli.commands.items()):
        found.append((name, group))
        if isinstance(group, click.Group):
            found.extend((f"{name} {child}", cmd) for child, cmd in sorted(group.commands.items()))
    return found


def _summary(command: click.Command) -> str:
    text = command.help or command.short_help or ""
    for line in text.strip().splitlines():
        if line.strip():
            return line.strip()
    return ""


def _arguments(command: click.Command) -> str:
    names = [
        str(param.name).upper()
        for param in command.params
        if isinstance(param, click.Argument) and param.name
    ]
    return " ".join(names)


def _options(command: click.Command) -> list[tuple[str, str, str]]:
    found: list[tuple[str, str, str]] = []
    for param in command.params:
        if not isinstance(param, click.Option) or not param.help:
            continue
        flags = ", ".join(param.opts)
        default = "" if param.default in (None, False) else str(param.default)
        found.append((flags, default, param.help))
    return found


def render() -> str:
    """The whole command reference as markdown."""
    lines = [
        "# Commands",
        "",
        "Generated by `legvise.tools.build_commands`. Do not edit.",
        "",
        "Every command the tree exposes, with its arguments, its options and",
        "their defaults. `legvise --help` shows the same thing one group at a",
        "time.",
        "",
    ]
    for path, command in commands():
        depth = "##" if " " not in path else "###"
        arguments = _arguments(command)
        heading = f"{depth} `legvise {path}{' ' + arguments if arguments else ''}`"
        lines.append(heading)
        lines.append("")
        summary = _summary(command)
        if summary:
            lines.append(summary)
            lines.append("")
        options = _options(command)
        if options:
            lines.append("| option | default | what it does |")
            lines.append("| --- | --- | --- |")
            for flags, default, help_text in options:
                shown = f"`{default}`" if default else ""
                lines.append(f"| `{flags}` | {shown} | {help_text} |")
            lines.append("")
    groups = sum(1 for path, _ in commands() if " " not in path)
    lines.append(f"{len(commands()) - groups} commands across {groups} groups.")
    return "\n".join(lines) + "\n"


def target() -> Path:
    """Where the reference is written."""
    return repo_root() / OUTPUT


def write() -> int:
    """Write the reference and return how many entries it covered."""
    path = target()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(), encoding="utf-8", newline="\n")
    return len(commands())


def is_current() -> bool:
    """True when the file on disk matches what the tree produces."""
    path = target()
    return path.exists() and path.read_text(encoding="utf-8") == render()


def main(argv: tuple[str, ...] = ()) -> int:
    """Write the reference, or check it is current."""
    args = argv or tuple(sys.argv[1:])
    if "--check" in args:
        if is_current():
            print("build_commands: current")
            return 0
        print(f"build_commands: {OUTPUT} is stale; run legvise.tools.build_commands")
        return 1
    count = write()
    print(f"build_commands: wrote {count} entries to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
