"""Write the domain vocabulary out, generated from the records that define it.

Every desk has a glossary and every glossary is out of date, because it is
written once by whoever joined most recently and then nobody touches it. This
one is generated from `legvise.model`: the record names, their first docstring
line, and every field with its type.

That is a narrower glossary than a person would write and it has one property a
person's does not, which is that it cannot be wrong. A field renamed in the code
is renamed here on the next run, and CI fails if nobody ran it.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path
from typing import NamedTuple

from legvise.tools.walk import SourceFile, repo_root, source_files

__all__ = ["OUTPUT", "Entry", "entries", "main", "render"]

OUTPUT = "docs/glossary.md"
MODEL_PREFIX = "legvise.model."


class Field(NamedTuple):
    """One attribute of a record, and how it is spelled in the code."""

    name: str
    annotation: str


class Entry(NamedTuple):
    """One record in the vocabulary."""

    module: str
    name: str
    summary: str
    fields: tuple[Field, ...]

    @property
    def is_record(self) -> bool:
        """True when the entry carries fields rather than just behaviour."""
        return bool(self.fields)


def _summary(node: ast.ClassDef) -> str:
    text = ast.get_docstring(node) or ""
    return text.strip().splitlines()[0] if text.strip() else ""


def _fields(node: ast.ClassDef) -> tuple[Field, ...]:
    found: list[Field] = []
    for item in node.body:
        if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
            found.append(Field(item.target.id, ast.unparse(item.annotation)))
    return tuple(found)


def _entries_in(source: SourceFile) -> list[Entry]:
    found: list[Entry] = []
    for node in source.tree.body:
        if not isinstance(node, ast.ClassDef) or node.name.startswith("_"):
            continue
        found.append(
            Entry(
                module=source.module.removeprefix("legvise."),
                name=node.name,
                summary=_summary(node),
                fields=_fields(node),
            )
        )
    return found


def entries() -> tuple[Entry, ...]:
    """Every record in `legvise.model`, in module then class order."""
    found: list[Entry] = []
    for source in source_files():
        if not source.module.startswith(MODEL_PREFIX):
            continue
        found.extend(_entries_in(source))
    return tuple(found)


def render() -> str:
    """The whole glossary as markdown."""
    lines = [
        "# Glossary",
        "",
        "Generated by `legvise.tools.build_glossary`. Do not edit.",
        "",
        "The records the desk keeps, taken from `legvise.model`. A field named",
        "here is the field the code uses; there is no second spelling.",
        "",
    ]
    current = ""
    for entry in entries():
        if entry.module != current:
            current = entry.module
            lines.append(f"## `{current}`")
            lines.append("")
        lines.append(f"### {entry.name}")
        lines.append("")
        if entry.summary:
            lines.append(entry.summary)
            lines.append("")
        if entry.fields:
            lines.append("| field | type |")
            lines.append("| --- | --- |")
            lines.extend(f"| `{field.name}` | `{field.annotation}` |" for field in entry.fields)
            lines.append("")
    records = sum(1 for entry in entries() if entry.is_record)
    lines.append(f"{len(entries())} entries, {records} of them records.")
    return "\n".join(lines) + "\n"


def target() -> Path:
    """Where the glossary is written."""
    return repo_root() / OUTPUT


def write() -> int:
    """Write the glossary and return how many entries it covered."""
    path = target()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(), encoding="utf-8", newline="\n")
    return len(entries())


def is_current() -> bool:
    """True when the file on disk matches what the model produces."""
    path = target()
    return path.exists() and path.read_text(encoding="utf-8") == render()


def main(argv: tuple[str, ...] = ()) -> int:
    """Write the glossary, or check it is current."""
    args = argv or tuple(sys.argv[1:])
    if "--check" in args:
        if is_current():
            print("build_glossary: current")
            return 0
        print(f"build_glossary: {OUTPUT} is stale; run legvise.tools.build_glossary")
        return 1
    count = write()
    print(f"build_glossary: wrote {count} entries to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
