"""Write the runbook out: a refusal came back, now what.

The rule book says what each clause means. It does not say what to do about
one, and at four in the morning those are different questions. An operator
reading `DEPTH.02 x41` in a scan summary wants the next command, not a
definition.

So this pairs every stage of the rule book with the commands that investigate
it, and every self check with the sentence its own module opens with. Both
halves are read out of the tree rather than written here, which is the only
reason a runbook is worth generating: a hand written one describes the tool as
it was on the day somebody had the time.

What is not generated is the advice. `REMEDIES` below is prose, kept short, and
it is the one thing in this file a person has to maintain. That is deliberate.
A runbook whose advice is derived from the code says nothing the code did not
already say.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Final

from legvise.rules import clause_codes, clauses_for_stage, stages
from legvise.tools.walk import package_root, repo_root, source_files

__all__ = ["OUTPUT", "checks", "main", "render", "remedy_for"]

OUTPUT = "docs/operations.md"

#: What to do about a refusal at each stage, and the command that shows it.
#: One line each. A runbook nobody finishes reading is a runbook.
REMEDIES: Final[dict[str, tuple[str, str]]] = {
    "BOOK": (
        "The feed sent something malformed. Read the levels back and compare "
        "them against what the venue is showing.",
        "legvise book levels VENUE SYMBOL bid",
    ),
    "STALE": (
        "Either the feed has stalled or the two venues are being polled too far "
        "apart. The confidence slope says which.",
        "legvise book confidence VENUE SYMBOL",
    ),
    "TICK": (
        "The instrument on file disagrees with the venue. Check the tick, the "
        "lot and the notional bounds against the venue's own listing.",
        "legvise instrument show VENUE SYMBOL",
    ),
    "DEPTH": (
        "The book cannot fill the size the desk wants, or filling it would "
        "sweep past the venue's depth limit. Read the depth at the limit.",
        "legvise book depth VENUE SYMBOL",
    ),
    "FEE": (
        "No fee tier resolved, which usually means the trailing volume was "
        "never recorded. Nothing prices until it is.",
        "legvise fee show VENUE",
    ),
    "BAND": (
        "Inventory is at a floor or over a ceiling. The report says what would "
        "square each asset and what has to move rather than trade.",
        "legvise report inventory",
    ),
    "CAP": (
        "The desk is at an exposure limit. A trim is the caps working; a stop "
        "means the gross cap is binding and nothing else will price.",
        "legvise inventory exposure",
    ),
    "EDGE": (
        "The edge did not clear the floor, which is the normal case. Count the "
        "clauses across the session before changing anything.",
        "legvise scan refusals --session SESSION",
    ),
}


def stage_rows() -> list[tuple[str, int, str, str]]:
    """Each stage, how many clauses it holds, what to do, and the command."""
    found: list[tuple[str, int, str, str]] = []
    for stage in stages():
        advice, command = REMEDIES.get(stage, ("", ""))
        found.append((stage, len(clauses_for_stage(stage)), advice, command))
    return found


def remedy_for(code: str) -> tuple[str, str]:
    """What to do about one clause, and the command to run."""
    return REMEDIES.get(code.split(".", 1)[0], ("", ""))


def checks() -> list[tuple[str, str]]:
    """Every self check and the first sentence of its own docstring."""
    found: list[tuple[str, str]] = []
    names = {path.stem for path in (package_root() / "tools").glob("check_*.py")}
    for source in source_files():
        name = source.module.rsplit(".", 1)[-1]
        if name not in names:
            continue
        found.append((name, _first_sentence(source.docstring() or "")))
    return sorted(found)


def _first_sentence(text: str) -> str:
    line = text.strip().splitlines()[0] if text.strip() else ""
    return line.rstrip(".")


def render() -> str:
    """The whole runbook as markdown."""
    lines = [
        "# Operations",
        "",
        "Generated by `legvise.tools.build_operations`. Do not edit.",
        "",
        "A refusal came back. This says what to do about it.",
        "",
        "## A clause fired",
        "",
        "Every refusal quotes a clause and the clause is stored on the plan, so",
        "start by counting them across the session rather than reading one.",
        "",
        "```",
        "legvise scan refusals --session SESSION",
        "```",
        "",
        "| stage | clauses | what it means | where to look |",
        "| --- | --- | --- | --- |",
    ]
    for stage, count, advice, command in stage_rows():
        shown = f"`{command}`" if command else "-"
        lines.append(f"| {stage} | {count} | {advice or '-'} | {shown} |")
    lines.extend(
        [
            "",
            "## Nothing priced at all",
            "",
            "A scan that considered no symbols is a desk that is not set up, not",
            "a quiet market. The desk report is the difference.",
            "",
            "```",
            "legvise report desk",
            "```",
            "",
            "## The numbers look wrong",
            "",
            "Read the book back and re-derive it. Nothing here can fail on a file",
            "this tool wrote and nothing else has touched.",
            "",
            "```",
            "legvise db verify",
            "```",
            "",
            "## The file is growing",
            "",
            "```",
            "legvise db prune --keep-days 30",
            "legvise db vacuum",
            "```",
            "",
            "The newest snapshot of every market survives whatever its age, and so",
            "does any session with a fill against it.",
            "",
            "## The self checks",
            "",
            "All of these run in CI and all of them run from `./check.sh`.",
            "",
            "| check | what it catches |",
            "| --- | --- |",
        ]
    )
    for name, summary in checks():
        lines.append(f"| `{name}` | {summary} |")
    lines.append("")
    lines.append(
        f"{len(clause_codes())} clauses across {len(stages())} stages, "
        f"and {len(checks())} self checks."
    )
    return "\n".join(lines) + "\n"


def target() -> Path:
    """Where the runbook is written."""
    return repo_root() / OUTPUT


def write() -> int:
    """Write the runbook and return how many stages it covered."""
    path = target()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(), encoding="utf-8", newline="\n")
    return len(stage_rows())


def is_current() -> bool:
    """True when the file on disk matches what the tree produces."""
    path = target()
    return path.exists() and path.read_text(encoding="utf-8") == render()


def main(argv: tuple[str, ...] = ()) -> int:
    """Write the runbook, or check it is current."""
    args = argv or tuple(sys.argv[1:])
    if "--check" in args:
        if is_current():
            print("build_operations: current")
            return 0
        print(f"build_operations: {OUTPUT} is stale; run legvise.tools.build_operations")
        return 1
    count = write()
    print(f"build_operations: wrote {count} stages to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
