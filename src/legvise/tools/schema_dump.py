"""Write the schema out as SQL, generated from the migrations that build it.

A hand written `schema.sql` beside a list of migrations is two descriptions of
one thing, and within a month they disagree. This one is generated: the
migrations run against an in-memory database, SQLite is asked what it made, and
the answer is written to `docs/schema.sql`.

`--check` compares instead of writing, which is what CI runs. A pull request
that adds a migration and forgets the dump fails there rather than leaving the
file stale.
"""

from __future__ import annotations

import sys
from pathlib import Path

from legvise.store.db import Database
from legvise.store.schema import MIGRATIONS, install
from legvise.tools.walk import repo_root

__all__ = ["OUTPUT", "main", "render"]

OUTPUT = "docs/schema.sql"
INSTALLED_AT = "2000-01-01T00:00:00+00:00"


def _objects(db: Database) -> list[tuple[str, str, str]]:
    rows = db.query(
        "SELECT type, name, sql FROM sqlite_master"
        " WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'"
        " ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name"
    )
    return [(str(r["type"]), str(r["name"]), str(r["sql"])) for r in rows]


def render() -> str:
    """The whole schema as SQL text."""
    db = Database.in_memory()
    try:
        install(db, applied_at=INSTALLED_AT)
        lines = [
            "-- Generated by legvise.tools.schema_dump. Do not edit.",
            f"-- Built from {len(MIGRATIONS)} migrations.",
            "",
        ]
        for kind, name, sql in _objects(db):
            lines.append(f"-- {kind} {name}")
            lines.append(f"{sql.strip()};")
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"
    finally:
        db.close()


def target() -> Path:
    """Where the dump is written."""
    return repo_root() / OUTPUT


def write() -> int:
    """Write the dump and return how many bytes it came to."""
    path = target()
    path.parent.mkdir(parents=True, exist_ok=True)
    body = render()
    path.write_text(body, encoding="utf-8", newline="\n")
    return len(body)


def is_current() -> bool:
    """True when the file on disk matches what the migrations produce."""
    path = target()
    if not path.exists():
        return False
    return path.read_text(encoding="utf-8") == render()


def main(argv: tuple[str, ...] = ()) -> int:
    """Write the dump, or check it is current."""
    args = argv or tuple(sys.argv[1:])
    if "--check" in args:
        if is_current():
            print("schema_dump: current")
            return 0
        print(f"schema_dump: {OUTPUT} is stale; run legvise.tools.schema_dump")
        return 1
    size = write()
    print(f"schema_dump: wrote {size} bytes to {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
